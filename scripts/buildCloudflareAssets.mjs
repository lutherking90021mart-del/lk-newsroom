import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const dist = resolve(root, "dist");
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

const rootFiles = ["index.html", "404.html", "ads.txt", "manifest.webmanifest", "pwa-install.js", "sw.js"];
for (const name of rootFiles) {
  try { await cp(resolve(root, name), resolve(dist, name)); }
  catch (error) { if (error && error.code !== "ENOENT") throw error; }
}
for (const name of ["assets", "pages", "styles", "js"]) {
  await cp(resolve(root, name), resolve(dist, name), { recursive: true });
}
await mkdir(resolve(dist, "js"), { recursive: true });
const config = [
  "// Generated by scripts/buildCloudflareAssets.mjs. Do not add Supabase secrets here.",
  'window.LK_SUPABASE_URL = "";',
  'window.LK_SUPABASE_ANON_KEY = "";',
  "window.LK_AGGREGATOR_API_URL = location.origin;",
  "window.LK_CLOUDFLARE_MODE = true;"
].join("\n") + "\n";
await writeFile(resolve(dist, "js/config.js"), config, "utf8");
await cp(resolve(root, "cloudflare/public-client.js"), resolve(dist, "js/supabase-client.js"));
await cp(resolve(root, "cloudflare/admin-migration.html"), resolve(dist, "admin-migration.html"));
console.log("Cloudflare public assets built into dist/. Server-only folders and environment files were not copied.");
